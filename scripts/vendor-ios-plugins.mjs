// Makes ios/App/App.xcodeproj open in Xcode with NO npm and NO CocoaPods on the Mac.
// `cap sync ios` writes ios/App/CapApp-SPM/Package.swift with plugin paths into node_modules, which does not
// exist on a machine without npm. This copies each plugin's Swift package into ios/App/LocalPackages/ (committed
// to git) and points Package.swift there. Run it after every `cap sync ios` (npm run sync does).
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(new URL('..', import.meta.url).pathname)
const spm = join(root, 'ios/App/CapApp-SPM/Package.swift')
const dest = join(root, 'ios/App/LocalPackages')
let text = readFileSync(spm, 'utf8')

const re = /path: "\.\.\/\.\.\/\.\.\/node_modules\/@capacitor\/([\w-]+)"/g
const found = [...text.matchAll(re)].map((m) => m[1])
if (!found.length) {
  console.log('vendor-ios-plugins: Package.swift already uses LocalPackages, nothing to do')
  process.exit(0)
}
mkdirSync(dest, { recursive: true })
for (const name of found) {
  const from = join(root, 'node_modules/@capacitor', name)
  const to = join(dest, name)
  if (!existsSync(from)) throw new Error(`missing ${from}: run npm ci first`)
  rmSync(to, { recursive: true, force: true })
  mkdirSync(to, { recursive: true })
  for (const f of ['Package.swift', 'LICENSE']) if (existsSync(join(from, f))) cpSync(join(from, f), join(to, f))
  cpSync(join(from, 'ios/Sources'), join(to, 'ios/Sources'), { recursive: true })
  if (existsSync(join(from, 'ios/Tests'))) cpSync(join(from, 'ios/Tests'), join(to, 'ios/Tests'), { recursive: true })
  console.log(`vendored @capacitor/${name}`)
}
text = text.replace(re, (_, name) => `path: "../LocalPackages/${name}"`)
text = text.replace('// DO NOT MODIFY THIS FILE - managed by Capacitor CLI commands', '// Generated by Capacitor CLI, then plugin paths rewritten to ../LocalPackages by scripts/vendor-ios-plugins.mjs\n// so Xcode opens this project without npm. Re-run `npm run sync` after changing plugins.')
writeFileSync(spm, text)
console.log('vendor-ios-plugins: Package.swift now points at ios/App/LocalPackages')
